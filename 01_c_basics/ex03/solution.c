#include <stdio.h>
int main ()
{
	int a=10;
	int b=20;
	printf("The sum is %d + %d=%d\n",a,b,a+b);
	printf("The difference is %d-%d=%d\n",a,b,a-b);
	printf("The multiplication is %d*%d=%d\n",a,b,a*b);
	float x=20;
	float y=10;
	printf("The division is %.2f/%.2f=%.2f\n",x,y,x/y);
	return 0;
}
